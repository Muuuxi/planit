  await interview.getByLabel('End time', { exact: true }).fill('15:30');
  await interview.getByLabel('Timezone', { exact: true }).selectOption('America/Los_Angeles');
  await interview.getByLabel('Course / Project').fill('Career');
  await interview.getByLabel('Priority', { exact: true }).selectOption('Medium');
