test('edit, add, delete and next-day 1 AM window update canonical items and capacity', async ({ page }) => {
  const event = calendar(page).getByRole('button', { name: 'Edit Weekly planning', exact: true });
  const top = await event.evaluate(el => (el as HTMLElement).style.top);
  await event.click();
  let editor = page.getByRole('complementary', { name: 'Event editor' });
  await editor.getByLabel('Start time', { exact: true }).fill('09:00');
  await editor.getByLabel('End time', { exact: true }).fill('09:45');
  await editor.getByRole('button', { name: 'Save commitment' }).click();
  expect(await event.evaluate(el => (el as HTMLElement).style.top)).not.toBe(top);
  await quickAction(page, 'Add event');
  editor = page.getByRole('complementary', { name: 'Event editor' });
  await editor.getByLabel('Title', { exact: true }).fill('Late work test');
  await editor.getByLabel('Date', { exact: true }).fill('2026-09-15');
  await editor.getByLabel('Start time', { exact: true }).fill('00:15');
  await editor.getByLabel('End time', { exact: true }).fill('00:45');
  await editor.getByLabel('Estimated energy / effort').selectOption('High');
  await editor.getByRole('button', { name: 'Save commitment' }).click();
  await expect(calendar(page).locator('.day-heading').nth(1)).toContainText('/ 6h');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('tab', { name: 'Calendar', exact: true }).click();
  await page.getByLabel('Calendar visible start time').selectOption('8');
  await page.getByLabel('Calendar visible end time').selectOption('25');
  await expect(calendar(page).locator('[data-date="2026-09-14"]').getByRole('button', { name: 'Edit Late work test' })).toBeAttached();
  await page.getByRole('button', { name: 'Close settings' }).click();
  await calendar(page).getByRole('button', { name: 'Edit Late work test' }).click();
  await editor.getByRole('button', { name: 'Delete commitment' }).click();
  await editor.getByRole('button', { name: 'Confirm delete' }).click();
  expect((await state(page)).some((item: { title: string }) => item.title === 'Late work test')).toBe(false);
  await expect(calendar(page).locator('.day-heading').nth(1)).toContainText('/ 7.5h');
  await page.reload();
  await expect(calendar(page).getByRole('button', { name: 'Edit Weekly planning', exact: true })).toContainText('9:00 AM');
});

