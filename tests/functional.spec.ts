test('voice retry, validation, deadline edits and cancellation', async ({ page }) => {
  const before = await state(page);
  await voice(page);
  const panel = page.getByRole('complementary', { name: 'Voice confirmation' });
  await panel.getByRole('article', { name: 'Final Interview' }).getByRole('button', { name: 'Remove' }).click();
  await panel.getByRole('article', { name: 'Online Assessment' }).getByRole('button', { name: 'Remove' }).click();
  await expect(panel.getByRole('button', { name: 'Confirm & Replan' })).toBeDisabled();
  await panel.getByRole('button', { name: 'Retry voice' }).click();
  await expect(panel.getByRole('heading', { name: 'Here’s what I understood' })).toBeVisible();
  await expect(panel.getByRole('article')).toHaveCount(2);
  const interview = panel.getByRole('article', { name: 'Final Interview' });
  await interview.getByRole('button', { name: 'Edit', exact: true }).click();
  await interview.getByLabel('End time', { exact: true }).fill('01:00');
  await panel.getByRole('button', { name: 'Confirm & Replan' }).click();
  await expect(panel.getByRole('alert')).toContainText('End must be after start');
  await interview.getByLabel('End time', { exact: true }).fill('03:00');
  await interview.getByRole('button', { name: 'Done editing' }).click();
  const assessment = panel.getByRole('article', { name: 'Online Assessment' });
  await assessment.getByRole('button', { name: 'Edit', exact: true }).click();
  await assessment.getByLabel('Deadline date', { exact: true }).fill('2026-09-19');
  await assessment.getByLabel('Deadline time', { exact: true }).fill('22:30');
  await assessment.getByLabel('Timezone', { exact: true }).selectOption('Asia/Shanghai');
  await assessment.getByRole('button', { name: 'Done editing' }).click();
  await page.screenshot({ path: 'test-results/voice-confirmation.png' });
  await panel.getByRole('button', { name: 'Confirm & Replan' }).click();
  await page.getByRole('button', { name: 'Preview Changes' }).click();
  await expect(calendar(page).locator('.deadline-chip').filter({ hasText: 'Online Assessment' })).toContainText('10:30 AM');
  await page.getByRole('button', { name: 'Keep Current Plan' }).click();
  expect(await state(page)).toEqual(before);
});
