import { quickAction } from './quickAction';
import { test, expect, type Page } from '@playwright/test';
const state = (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('planit-items-v4')!));
const calendar = (page: Page) => page.getByRole('region', { name: 'Weekly schedule' });
async function voice(page: Page) {
  await quickAction(page, 'Speak a change');
  await expect(page.getByRole('heading', { name: 'Here’s what I understood' })).toBeVisible();
}
test.beforeEach(async ({ page }) => { page.on('pageerror', error => { throw error; }); await page.clock.setFixedTime(new Date('2026-09-14T16:00:00Z')); await page.goto('/'); await page.getByRole('button', { name: 'Explore Demo', exact: true }).click(); await page.getByRole('button', { name: 'Expand context sidebar' }).click(); });

test('settings update range, 24-hour mode, timezone dates and persist after reload', async ({ page }) => {
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('tab', { name: 'Calendar', exact: true }).click();
  const settings = page.getByRole('complementary', { name: 'Calendar settings' });
  await expect(settings.getByLabel('Calendar visible start time')).toHaveValue('6');
  await expect(settings.getByLabel('Calendar visible end time')).toHaveValue('24');
  await settings.getByLabel('Calendar visible start time').selectOption('8');
  await settings.getByLabel('Calendar visible end time').selectOption('25');
  await expect(calendar(page).locator('.time-axis span').first()).toHaveText('8:00 AM');
  await expect(calendar(page).locator('.time-axis span').last()).toHaveText('1:00 AM +1d');
  await settings.getByLabel('Time format', { exact: true }).selectOption('24');
  await expect(calendar(page).locator('.time-axis span').first()).toHaveText('08:00');
  await settings.getByRole('switch').check();
  await expect(calendar(page).locator('.time-axis span').first()).toHaveText('00:00');
  await expect(calendar(page).locator('.time-axis span').last()).toHaveText('24:00');
  await expect(settings.getByLabel('Calendar visible start time')).toBeDisabled();
  const before = await state(page);
  await settings.getByLabel('Search timezones').fill('China');
  await settings.getByLabel('Timezone', { exact: true }).selectOption('Asia/Shanghai');
  await expect(calendar(page).getByRole('button', { name: 'Edit Weekly planning', exact: true })).toContainText('20:00');
  await expect(calendar(page).locator('[data-date="2026-09-15"]').getByRole('button', { name: 'Edit Portfolio deep work' })).toContainText('04:00');
  expect(await state(page)).toEqual(before);
  await page.screenshot({ path: 'test-results/settings.png' });
  await page.reload();
  await expect(calendar(page).getByRole('button', { name: 'Edit Weekly planning', exact: true })).toContainText('20:00');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('tab', { name: 'Calendar', exact: true }).click();
  await expect(settings.getByRole('switch')).toBeChecked();
  await settings.getByRole('switch').uncheck();
  await expect(calendar(page).locator('.time-axis span').first()).toHaveText('08:00');
});

